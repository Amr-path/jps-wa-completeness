import time
from myjps import Inst, bottleneck, replay
cases=[('climb_1 ev4 w=1',1.0,9,(8,8),(4,4),[(1, 4), (2, 3), (3, 6), (5, 2), (6, 5), (6, 6)]),
('climb_2 ev483 w=2',2.0,9,(2,8),(4,4),[(0, 0), (0, 2), (0, 6), (0, 8), (1, 0), (2, 0), (2, 1), (2, 3), (2, 6), (3, 1), (3, 6), (3, 7), (4, 7), (5, 0), (5, 2), (6, 5), (6, 6), (6, 8), (7, 2), (7, 3), (8, 1), (8, 7)]),
('climb_3 ev2575 w=1e6',1e6,9,(8,7),(4,4),[(0, 2), (0, 8), (1, 0), (1, 4), (2, 2), (2, 3), (2, 7), (3, 0), (3, 6), (5, 0), (5, 1), (5, 2), (6, 0), (6, 2), (6, 5), (6, 6), (7, 0), (7, 2), (7, 3), (8, 1), (8, 3), (8, 4), (8, 5), (8, 6)])]
for nm,w,N,s,t,bl in cases:
    I=Inst(N,bl,s,t); t0=time.time(); st,v,o=bottleneck(I,w,cap=3_000_000)
    rb=replay(Inst(N,bl,s,t),w,o) if o else None
    print(nm,st,repr(v),'replay',rb,'%.0fs'%(time.time()-t0),flush=True)
