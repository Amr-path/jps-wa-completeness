"""Replay a pop order in the faithful model and print, at every pop, the popped entry (cell, g, parent, arrival
direction, f_w), the f-minimum of Open, the slack, the entries generated by the expansion and the full Open list.
Usage: import trace; trace.run(grid, s, t, w, order)"""
import sys, math
sys.path.insert(0, '/path/to/jps-wa/verification/round3'); sys.path.insert(0, '/path/to/jps-wa/ref')
from core import Model, pinwheel1, octile, grid_to_str

DN = {(1, 0): 'E', (-1, 0): 'W', (0, 1): 'S', (0, -1): 'N', (1, 1): 'SE', (1, -1): 'NE', (-1, 1): 'SW', (-1, -1): 'NW', (0, 0): '0'}

def run(grid, s, t, w, order, verbose=True):
    M = Model(grid, s)
    h = lambda c: octile(c[0], c[1], t[0], t[1])
    od = {s: (0.0, None)}; closed = set(); visited = {s}
    log = []
    for step, x in enumerate(order):
        gx, px = od[x]
        d = M.dir_from(x, px)
        fx = gx + w * h(x)
        fmin = min(g + w * h(c) for c, (g, p) in od.items())
        jps, vis = M.expand(x, d)
        closed.add(x); del od[x]; visited |= vis
        gen = []
        for (j, c) in jps:
            jg = gx + c
            if j in closed: gen.append((j, jg, 'CLOSED-dropped')); continue
            if jg < od.get(j, (math.inf,))[0] - 1e-12:
                old = od.get(j); od[j] = (jg, x); gen.append((j, jg, 'new' if old is None else f'improves {old[0]:.2f} from {old[1]}'))
            else:
                gen.append((j, jg, f'stale (open g={od[j][0]:.2f} from {od[j][1]})'))
        rec = dict(step=step, x=x, g=gx, p=px, d=DN[d], f=fx, fmin=fmin, slack=fx - fmin, gen=gen,
                   open=sorted(((g + w * h(c), c, g, p) for c, (g, p) in od.items())))
        log.append(rec)
        if verbose:
            print(f"[{step:2d}] pop {x} g={gx:.3f} from {px} dir={DN[d]} h={h(x):.3f} f={fx:.3f} fmin={fmin:.3f} slack={fx-fmin:.3f}")
            for j, jg, st in gen: print(f"        -> {j} g={jg:.3f} h={h(j):.3f} f={jg + w*h(j):.3f} {st}")
            print("        open:", ', '.join(f"{c}:{f:.2f}(g{g:.2f}<-{p})" for f, c, g, p in rec['open']))
    return log, visited, closed

if __name__ == '__main__':
    g, t = pinwheel1(N=9)
    s = (1, 1)
    order = [(1,1),(2,2),(1,4),(2,5),(2,7),(4,7),(5,6),(4,5),(7,6),(7,4),(6,3),(5,4),(6,1),(7,2),(4,3),(3,2),(3,4),(4,1)]
    print(grid_to_str(g, s, t))
    log, visited, closed = run(g, s, t, 1.0, order)
    comp = Model(g, s).component()
    print('never visited:', sorted(comp - visited))
