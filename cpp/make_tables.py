"""LaTeX tables for the experiments section from results/*.csv.

Table (per collection, w in {1,2,10}): for each algorithm, mean expansions and mean scanned cells from the
full sweep and mean time (ms) from the dedicated timing run; max/mean cost ratios and totals as comments.
"""
import csv, glob, os
from collections import defaultdict

import sys
R = '/home/claude/jps-wa/results'
RT = '/home/claude/jps-wa/results_time'   # dedicated timing run (every 100th instance, w in {1,2,10})
A = defaultdict(lambda: dict(n=0, exp=0, scan=0, us=0, maxr=0.0, viol=0, nf=0, sumr=0.0))
for fn in glob.glob(os.path.join(R, '*.csv')):
    coll = os.path.basename(fn).split('.')[0]
    with open(fn) as f:
        for row in csv.DictReader(f):
            if row['opt'] == 'inf': continue
            a = A[(coll, float(row['w']), row['alg'])]
            a['n'] += 1; a['exp'] += int(row['expanded']); a['scan'] += int(row['scanned']); a['us'] += int(row['micros'])
            if row['found'] == '1':
                r = float(row['ratio']); a['maxr'] = max(a['maxr'], r); a['sumr'] += r
            else: a['nf'] += 1
            if row['bound_ok'] == '0': a['viol'] += 1

T = defaultdict(lambda: dict(n=0, us=0))
for fn in glob.glob(os.path.join(RT, '*.csv')):
    coll = os.path.basename(fn).split('.')[0]
    with open(fn) as f:
        for row in csv.DictReader(f):
            if row['opt'] == 'inf': continue
            a = T[(coll, float(row['w']), row['alg'])]; a['n'] += 1; a['us'] += int(row['micros'])
colls = ['dao', 'da2', 'bg512', 'sc1', 'rooms', 'random', 'mazes']
algs = [('jps_cell', 'cell'), ('jps_state', 'state'), ('jps_fls', 'FLS'), ('wastar', 'WA*')]
ws = [1, 2, 10]
tot_viol = tot_nf = tot_n = 0
print('% generated by cpp/make_tables.py')
print(r'\begin{tabular}{llrrrrrrrrrrrr}')
print(r'\toprule')
print(r' & & \multicolumn{4}{c}{expansions} & \multicolumn{4}{c}{scanned cells (thousands)} & \multicolumn{4}{c}{time (ms)}\\')
print(r'\cmidrule(lr){3-6}\cmidrule(lr){7-10}\cmidrule(lr){11-14}')
print(r'set & $w$ & ' + ' & '.join(l for _, l in algs) + ' & ' + ' & '.join(l for _, l in algs) + ' & ' + ' & '.join(l for _, l in algs) + r'\\')
print(r'\midrule')
for c in colls:
    first = True
    for w in ws:
        if (c, w, 'jps_cell') not in A: continue
        cells = []
        for key in ('exp', 'scan', 'us'):
            for alg, _ in algs:
                a = A[(c, w, alg)]; n = max(a['n'], 1)
                v = a[key] / n
                if key == 'scan': cells.append('--' if alg == 'wastar' else f'{v/1000:.1f}')
                elif key == 'us':
                    t = T.get((c, w, alg)); cells.append(f"{t['us']/t['n']/1000:.2f}" if t and t['n'] else '--')
                else: cells.append(f'{v:.0f}')
        print(f"{c if first else ''} & {w:g} & " + ' & '.join(cells) + r'\\')
        first = False
    print(r'\midrule')
print(r'\bottomrule')
print(r'\end{tabular}')
print()
print('% max cost ratio per (set, w): cell / state / FLS / WA*')
for c in colls:
    for w in [1, 1.5, 2, 3, 5, 10]:
        if (c, w, 'jps_cell') not in A: continue
        rs = [A[(c, w, alg)]['maxr'] for alg, _ in algs]; ns = [A[(c, w, alg)]['n'] for alg, _ in algs]
        mr = [A[(c, w, alg)]['sumr'] / max(A[(c, w, alg)]['n'], 1) for alg, _ in algs]
        print(f"% {c} w={w}: n={ns[0]} max " + ' / '.join(f'{r:.3f}' for r in rs) + '   mean ' + ' / '.join(f'{r:.4f}' for r in mr))
for k, a in A.items():
    tot_viol += a['viol']; tot_nf += a['nf']; tot_n += a['n']
print(f'% total solvable instance-runs {tot_n}, bound violations {tot_viol}, not found {tot_nf}')
